// Sandbox (runtime)
// ─────────────────────────────────────────────────────────────────────────

export interface SandboxOptions {
  /**
   * Maximum number of runs executing at once. Additional callers queue FIFO
   * until a run finishes; a queued caller's `AbortSignal` is honoured while
   * it waits, so `AbortSignal.timeout()` composes as a queue-wait bound —
   * there is no separate timeout option.
   *
   * This is an admission number, not a socket count: connections to the
   * runtime process open on demand as runs need them and are reused for the
   * process lifetime (`SandboxStats.openConnections` reports the live
   * count). Multiple MCP agents / concurrent callers run in parallel up to
   * this limit.
   *
   * Overridable in both directions: lowering it leaves cores to the host
   * app; raising it above the core count pays only for workloads that spend
   * their time suspended on host calls rather than computing.
   *
   * This caps *concurrent runs* only. How many isolates stay resident
   * (warm instances included) is the memory budget's job — see
   * `memoryBudgetMb`. There is no instance-count cap of any kind, so
   * idle warm instances may outnumber the running count here, or fall below
   * it under memory pressure.
   *
   * Must be an integer ≥ 1 — anything else throws at `createSandbox()`
   * (`0` would queue every run forever).
   *
   * Defaults to `os.availableParallelism()`.
   */
  maxConcurrentRuns?: number

  /**
   * Hard cap on memory each isolate can use, in megabytes. Covers the V8
   * heap and all external `ArrayBuffer` allocations; also determines the
   * BridgeResponse frame read cap (the sandbox cannot receive a response
   * larger than its own memory budget).
   *
   * Uniform across ALL isolates of this Sandbox and settable only here —
   * never per run or per prefix. The cap is baked into the isolate at
   * creation, and prefix runs reuse warm isolates, so a per-run value is
   * structurally impossible; a uniform cap also keeps capacity math simple
   * (slots × cap). Memory accumulates across calls on a warm instance —
   * hitting the cap taints the instance and the next call cold-starts.
   *
   * Zero means no cap.
   * @default 128
   */
  memoryMb?: number

  /**
   * The runtime's memory mark, in megabytes (celld's model, one
   * mark). The runtime watches its own process RSS against it: at/above
   * the mark it evicts idle warm instances by `heapUsed × idleTime` score
   * (highest first) AND stops pooling new instances — prefix runs without
   * an idle instance execute on cold one-off isolates — until RSS falls
   * back to 80 % of the mark (hysteresis, so eviction doesn't flap).
   * Reusing an already-warm instance stays allowed under pressure; it adds
   * no memory. Correctness never depends on warmth; the only observable
   * cost of eviction is cold-start latency. There is no instance-count
   * cap — concurrency is bounded by `maxConcurrentRuns`, memory by this mark.
   *
   * `0` disables the mark entirely (nothing bounds warmth then except
   * `dispose()`). Independent of `memoryMb`: RSS is measured, not derived
   * from per-isolate caps.
   *
   * Default: the memory available to this process — container/cgroup-aware
   * via `process.constrainedMemory()`, falling back to `os.totalmem()` —
   * minus a safety net of max(512 MB, 25 %) for the Node host, the Rust
   * runtime, and whatever the embedding service keeps in memory per isolate.
   * Services with a large per-isolate host cache should set this lower.
   * On a host too small for that subtraction the default floors at 64 MB
   * (with a warning on stderr) rather than reaching 0 and disabling the
   * mark: memory-starved hosts get aggressive eviction, never no protection.
   * The floor applies to the default only — an explicit `0` still opts out.
   * Explicit values are clamped to `Number.MAX_SAFE_INTEGER` bytes (above
   * that the byte math stops being exact) and a negative value to `0`; a
   * non-finite one throws.
   */
  memoryBudgetMb?: number

  /**
   * Override the path to the Rust V8 binary.
   * Default: auto-detect from \@iso4/v8-* platform packages.
   */
  binaryPath?: string
}

/**
 * A point-in-time capacity/usage snapshot from `sandbox.stats()`.
 * The runtime-side numbers are mutually consistent (taken under one
 * registry lock); `queueDepth` is a separate host-side read taken after
 * the round trip. All of it is stale the moment it returns —
 * diagnostics, not synchronization.
 */
export interface SandboxStats {
  /**
   * Isolates executing right now: one-off `run()`s plus prefix runs on warm
   * instances.
   */
  activeRuns: number
  /**
   * Callers queued for a free run slot (`maxConcurrentRuns` runs are
   * already executing).
   */
  queueDepth: number
  /**
   * Host-side count of runtime connections as the pool tracks them (the
   * dedicated `stats()` control connection not included). Runs are
   * multiplexed onto shared connections — several concurrent runs per
   * connection, another opened only when all are at the internal
   * per-connection cap — and connections are kept for the process lifetime,
   * so this rises to roughly the concurrency high-water mark divided by the
   * cap and stays there. Capacity is `maxConcurrentRuns`, an admission
   * number decoupled from sockets. It is a ledger, not a per-read socket
   * probe: a connection that died stays counted until the next run
   * observes and replaces it.
   */
  openConnections: number
  /**
   * Resident warm instances — busy plus idle. Bounded by memory (the RSS
   * mark), not by a count.
   */
  warmInstances: number
  /**
   * Idle warm instances ready to serve their prefix without a cold start.
   */
  idleInstances: number
  /**
   * Summed heap of the idle instances in bytes, each measured after its
   * last call (a busy instance's current heap is unknown mid-call).
   */
  idleHeapBytes: number
  /**
   * The memory mark the runtime sheds against, in bytes —
   * `memoryBudgetMb` as the runtime received it. 0 = watermarks disabled.
   * Utilization is `rssBytes / budgetBytes`.
   */
  budgetBytes: number
  /**
   * The runtime process's resident set size in bytes at snapshot time —
   * the signal the mark acts on. 0 when the platform offers no reader.
   */
  rssBytes: number
  /**
   * True while the runtime is shedding: RSS reached the budget and
   * has not yet fallen back to 80 % of it. While shedding, idle instances
   * are evicted by score and new warm admissions stop (prefix runs without
   * an idle instance degrade to cold one-off isolates).
   */
  underPressure: boolean
  /**
   * Per-prefix instance counts, keyed by prefix id — saturation of a single
   * hot prefix is diagnosable here.
   */
  prefixes: Record<string, { idle: number, busy: number }>
}

export interface Sandbox {
  /**
   * Execute a piece of JavaScript in a fresh V8 isolate.
   * For repeated use with a shared context, prefer prepare() + prefix.execute().
   *
   * With `call`, the freshly evaluated module's export at `call.export` is
   * invoked and the result carries its return `value` instead of `exports`:
   *
   * ```ts
   * await sandbox.run({
   *   code: `export default { async fetch(request) { return new Response('hi') } }`,
   *   call: { export: 'default.fetch', args: [request] },
   * })
   * ```
   */
  run: {
    (options: RunCallOptions): Promise<CallResult>
    (options: RunOptions): Promise<RunResult>
  }

  /**
   * Load a module once and read its serializable exports — the
   * deploy/registration path (IaC-style declaration exports read when a
   * function is created, never per request). Builds no prefix and retains
   * nothing. Function exports are skipped and reported, so a module that
   * also exports handlers reads cleanly. Rejects on compile/runtime errors,
   * like `prepare()`.
   */
  readExports: (options: ReadExportsOptions) => Promise<ReadExportsResult>

  /**
   * Validate and prepare a prefix of code for repeated runs.
   *
   * The type parameter `G` is inferred from the `globals` you pass and flows
   * into the returned `Prefix<G>`. This lets TypeScript enforce at the call
   * site that `prefix.run()` can only rebind names declared here:
   *
   * ```ts
   * const prefix = await sandbox.precompile({
   *   globals: { fetch: myHandler, myTool: otherHandler },
   * })
   * // prefix: Prefix<{ fetch: ..., myTool: ... }>
   *
   * prefix.run({ globals: { fetch: newHandler } })          // ✅
   * prefix.run({ globals: { undeclared: someHandler } })    // ❌ TS error
   * ```
   *
   * Globals declared here serve as **default** implementations for all runs.
   * `prefix.run()` may override any subset; omitted names reuse the default.
   */

  /**
   * eslint-disable \@typescript-eslint/no-empty-object-type
   */
  prepare: <
    G extends HostGlobals = {},
    M extends Imports = {},
  >(
    options: PrecompileOptions<G, M>,
  ) => Promise<Prefix<G, M>>

  /**
   * @deprecated Renamed to {@link Sandbox.prepare}. `precompile` stays as an
   * alias (identical behavior) and is slated for removal in a future major.
   */
  precompile: <
    G extends HostGlobals = {},
    M extends Imports = {},
  >(
    options: PrecompileOptions<G, M>,
  ) => Promise<Prefix<G, M>>

  /**
   * A point-in-time capacity/usage snapshot: active runs, queue
   * depth, warm-instance counts and their measured memory. Served over a
   * dedicated control connection, so it answers even while every run slot
   * is busy. See {@link SandboxStats}.
   */
  stats: () => Promise<SandboxStats>

  /**
   * Tear down the Rust process. Outstanding prefixes are invalidated.
   */
  dispose: () => Promise<void>

  /**
   * Enables `await using sandbox = await createSandbox()` syntax.
   */
  [Symbol.asyncDispose]: () => Promise<void>

  readonly alive: boolean
}

export type CreateSandbox = (options?: SandboxOptions) => Promise<Sandbox>

