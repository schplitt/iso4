export interface RunOptions {
  code: string
  limits?: ResourceLimits
  globals?: HostGlobals
  imports?: Imports
  signal?: AbortSignal
  filename?: string
}

/**
 * `run()` options with a call: the module is evaluated, then
 * `call.export` is resolved against its freshly evaluated exports and
 * invoked. The result carries the function's return {@link CallSuccess.value}
 * instead of `exports` — never both.
 */
export interface RunCallOptions extends RunOptions {
  call: CallTarget
}

/**
 * Options for `sandbox.readExports()` — the deploy/registration path: load a
 * module once and read its declaration exports (IaC-style limits, connection
 * requirements, …). Function-valued exports are absent and reported in
 * {@link ReadExportsResult.skippedExports}, so reading the declarations of a
 * module that also exports handlers is not an error.
 */
export interface ReadExportsOptions {
  code: string
  limits?: ResourceLimits
  filename?: string
}

/**
 * What `sandbox.readExports()` resolves to. Unlike `run()`, failures reject
 * the returned promise (like `prepare()`), since the deploy path treats a
 * broken module as exceptional rather than as a result variant.
 */
export interface ReadExportsResult {
  exports: SandboxExports
  /**
   * Export names absent from `exports` because their value cannot cross the
   * boundary — see {@link RunSuccess.skippedExports}.
   */
  skippedExports: string[]
}

// ─────────────────────────────────────────────────────────────────────────
// Result
// ─────────────────────────────────────────────────────────────────────────

/**
 * Why a run was aborted — whatever value was passed to the aborting
 * `AbortController.abort(reason)` (or left `undefined`). Opaque to iso4 and
 * surfaced verbatim on {@link RunAborted.reason}; a consumer built on top
 * (e.g. a durable-workflow kernel expressing "suspend") gives it meaning.
 */
export type AbortReason = unknown

export type RunResult = RunSuccess | RunFailure | RunAborted

/**
 * Result of a run that carried a {@link CallTarget}: on success the called
 * function's return value replaces `exports` — never both. Failures and
 * aborts are shared with {@link RunResult}.
 */
export type CallResult = CallSuccess | RunFailure | RunAborted

/**
 * The success arm of a {@link CallResult}. Logs, timings, and bridge records
 * are identical to {@link RunSuccess}; only the value slot differs.
 */
export interface CallSuccess {
  status: 'completed'
  ok: true
  /**
   * The called function's return value — awaited first when the function
   * returned a Promise. Anything V8's serialization format carries arrives
   * as a real instance, including a `Response`.
   */
  value: unknown
  stdout: string[]
  stderr: string[]
  durationMs: number
  cpuTimeMs: number
  bridgeCalls: BridgeCallEntry[]
  /**
   * `used_heap_size` of the isolate that served this call, measured after
   * the call settled. Reported for prefix calls (warm instances);
   * `undefined` for one-off `sandbox.run({ call })`.
   */
  heapUsedBytes?: number
  /**
   * Present when the call registered background work with `waitUntil` —
   * see {@link RunSuccess.waitUntil}. Never rejects.
   */
  waitUntil?: Promise<WaitUntilResult>
}

/**
 * Metadata for a single bridge call attempt, recorded by the Rust runtime on
 * the run's own clock. No payloads — names, timing, and sizes only — so
 * recording is cheap enough to stay always-on. Unbounded: every attempt gets
 * an entry (~100 bytes); consumers that only care about a subset filter the
 * list themselves.
 */
export interface BridgeCallEntry {
  /**
   * The name sandbox code called. Plain globals appear as-is (`fetch`),
   * shimmed globals under their public name (not the private stub), and
   * host-module import leaves as `<specifier>.<path>` (e.g.
   * `tools:search.query`).
   */
  name: string
  /**
   * Offset from run start to the attempt, in milliseconds — same clock as
   * the result's `durationMs`, so entries line up on a run timeline.
   */
  startMs: number
  /**
   * Round-trip time the sandbox waited for the response (host handler + IPC),
   * in milliseconds. For calls still unanswered when the run ended
   * (timeout/abort): the time until the run ended. `0` for blocked attempts.
   */
  durationMs: number
  /**
   * Serialized size of the call payload (callId + target + arguments) in
   * bytes — the same size `maxBridgeCallBytes` is enforced against. `0` for
   * attempts blocked before argument serialization.
   */
  argBytes: number
  /**
   * Serialized size of the successful response value in bytes. `0` when the
   * handler failed or the call never settled.
   */
  responseBytes: number
  /**
   * `true` when the host handler resolved and its response reached the
   * sandbox. `false` for handler errors, blocked attempts, and calls still
   * in flight when the run ended.
   */
  ok: boolean
  /**
   * `true` when the attempt was blocked inside the runtime (`maxBridgeCalls`
   * exceeded, payload over `maxBridgeCallBytes`, function argument) and never
   * reached the host.
   */
  blocked: boolean
}

/**
 * Outcome of a run's `waitUntil` grace phase, delivered through
 * {@link RunSuccess.waitUntil} / {@link CallSuccess.waitUntil}. The promise
 * always **resolves** (never rejects), so ignoring it — the intended common
 * case — produces no unhandled-rejection noise.
 */
export interface WaitUntilResult {
  /**
   * `settled`: every registered promise finished within the grace budget.
   * `truncated`: the budget (or a host abort) cut the work short.
   * `failed`: at least one registered promise rejected — a normal outcome,
   * the code finished via its error path; the rest were still driven.
   */
  status: 'settled' | 'truncated' | 'failed'
  /**
   * Wall time of the grace phase (after the result shipped), ms.
   */
  durationMs: number
  /**
   * Active V8 execution time during the grace phase, ms.
   */
  cpuTimeMs: number
  /**
   * Console lines written during the grace phase — the run's own lines
   * arrived on the result itself.
   */
  stdout: string[]
  stderr: string[]
  /**
   * Bridge calls attempted during the grace phase.
   */
  bridgeCalls: BridgeCallEntry[]
  /**
   * The first rejection when `status === 'failed'`, or the fatal error that
   * ended a truncated phase, when one exists.
   */
  error?: { name: string, message: string }
}

/**
 * `status` is the primary discriminant across all three outcomes; `ok` is kept
 * as a convenience alias for `status === 'completed'`, so the common guard
 * stays `if (result.ok)`. Reach for `switch (result.status)` when a deliberate
 * abort must be told apart from a genuine failure.
 */
export interface RunSuccess {
  status: 'completed'
  ok: true
  exports: SandboxExports
  /**
   * Export names absent from `exports` because their value cannot cross the
   * boundary — a function (`export default { fetch }`), a Promise, or a value
   * whose serialization failed. Skipping is never fatal; the names are
   * reported here so nothing is silently hidden.
   *
   * A Promise is skipped **whatever its state**: the export path never awaits,
   * so `export default Promise.resolve(42)` is dropped exactly like a pending
   * one. Export the value instead — `export default await something()` — which
   * works because the module's own evaluation settles before the runtime reads
   * the namespace. `prefix.call()` is the opposite: it awaits a returned
   * Promise and resolves to its value.
   */
  skippedExports: string[]
  /**
   * Lines this run wrote to `console.log` / `.debug` / `.info`, capped by
   * `limits.maxStdoutBytes`. Prefix code shares the same console: when a run
   * cold-starts a warm instance, what the prefix logged while evaluating
   * arrives here once, on that run's result, ahead of the run's own lines.
   */
  stdout: string[]
  /**
   * Same as {@link RunSuccess.stdout}, for `console.warn` / `.error`.
   */
  stderr: string[]
  /**
   * Wall-clock time of the run (start of execution to result), measured in
   * the runtime. Milliseconds with microsecond resolution.
   */
  durationMs: number
  /**
   * Active V8 execution time — time spent waiting on host bridge calls is
   * excluded. Milliseconds with microsecond resolution. The remainder
   * (`durationMs - cpuTimeMs`) is bridge waits plus scheduling.
   */
  cpuTimeMs: number
  /**
   * One entry per bridge call the sandbox attempted, in attempt order —
   * including attempts blocked by limits ({@link BridgeCallEntry.blocked}).
   * Recorded by the Rust runtime.
   */
  bridgeCalls: BridgeCallEntry[]
  /**
   * `used_heap_size` of the isolate that served this run, measured after the
   * run settled. Reported for prefix runs — warm instances keep their
   * heap between calls, and this number feeds eviction. `undefined` for
   * one-off `sandbox.run()` runs, whose isolate is disposed with the run.
   */
  heapUsedBytes?: number
  /**
   * Present when the run registered background work with `waitUntil`:
   * the value in this result was delivered early, the work keeps running
   * runtime-side, and this promise resolves with the grace phase's outcome
   * once it ends. `undefined` for every run that registered nothing. Safe to
   * ignore — it never rejects.
   */
  waitUntil?: Promise<WaitUntilResult>
}

export interface RunFailure {
  status: 'failed'
  ok: false
  error: RunError
  stdout: string[]
  stderr: string[]
  durationMs: number
  cpuTimeMs: number
  bridgeCalls: BridgeCallEntry[]
  /**
   * `used_heap_size` of the isolate that served this run, measured after the
   * run settled. Reported for prefix runs — warm instances keep their
   * heap between calls, and this number feeds eviction. `undefined` for
   * one-off `sandbox.run()` runs, whose isolate is disposed with the run.
   */
  heapUsedBytes?: number
}

/**
 * The run was stopped by an abort — a pre-aborted or mid-run `signal` passed to
 * `run()`, or a host handler that aborted the run. A deliberate outcome, not a
 * crash: `error` is retained (its `code` is always `ERR_ABORTED`) so existing
 * `!result.ok` / `error.code` checks keep working, and `reason` carries the
 * value handed to `abort(reason)`.
 */
export interface RunAborted {
  status: 'aborted'
  ok: false
  error: RunError
  reason?: AbortReason
  stdout: string[]
  stderr: string[]
  durationMs: number
  cpuTimeMs: number
  /**
   * Bridge calls recorded before the abort landed. Populated when the runtime
   * terminates gracefully — the common case, where the run was suspended
   * awaiting a bridge response. Empty (and `durationMs`/`cpuTimeMs` zero) only
   * when graceful termination falls back to socket teardown — e.g. a run
   * aborted while stuck in a tight synchronous loop, or a signal already
   * aborted at run entry.
   */
  bridgeCalls: BridgeCallEntry[]
}

export type SandboxExports = {
  /**
   * Value of `export default` in user code, or `undefined`.
   */
  default: unknown
} & {
  /**
   * Named exports live directly on the export object.
   */
  [name: string]: unknown
}

export interface RunError {
  code: RunErrorCode
  name: string
  message: string
  /**
   * Stack trace of the thrown error. `name`/`message`/`stack` are reserved:
   * they are always read from the error's dedicated properties and never
   * appear inside `fields`, so a thrown object cannot spoof them there.
   */
  stack?: string
  /**
   * All other own enumerable properties of the thrown error (everything
   * except name/message/stack), e.g. `status`, `reason`, or a `data` payload
   * from a custom error class — nested here so nothing can collide with
   * `code`. Present for ERR_USER_CODE and ERR_HOST_BRIDGE when the thrown
   * value is an object with serializable own properties.
   */
  fields?: Record<string, unknown>
  /**
   * Present only for `ERR_INSTANCE_RESET`: what interrupted the co-resident
   * run that took the shared instance down with it.
   */
  resetCause?: ResetCause
  /**
   * Present only for `ERR_INSTANCE_RESET`: the wire run id of the run whose
   * interruption reset the instance — an opaque number, but stable across
   * the victims of one reset, so they can be correlated.
   */
  culpritRunId?: number
}

/**
 * Why a shared instance was reset under an innocent victim — see
 * `RunError.resetCause`.
 */
export type ResetCause = 'cpu' | 'memory' | 'wall' | 'abort' | 'internal'

export type RunErrorCode
  = | 'ERR_USER_CODE'
    | 'ERR_MEMORY_LIMIT'
    | 'ERR_CPU_TIMEOUT'
    | 'ERR_WALL_TIMEOUT'
    | 'ERR_ABORTED'
    | 'ERR_MODULE_NOT_FOUND'
    | 'ERR_COMPILE'
    | 'ERR_FUNCTION_ARGUMENT_NOT_SUPPORTED'
    | 'ERR_EXPORT_NOT_SERIALIZABLE'
    /**
     * A registered host type (`Request`, `Response`, …) cannot cross this
     * boundary in this position — an unimplemented tag, or content that is not
     * self-contained such as a stream body. See `docs/protocol.md` §4.4.5.
     */
    | 'ERR_TYPE_NOT_SERIALIZABLE'
    | 'ERR_EXPORT_TOO_LARGE'
    /**
     * A `call.export` path did not resolve against the module's exports, or
     * resolved to a value that is not callable. The message says which and
     * names the path.
     */
    | 'ERR_CALL_TARGET_NOT_FOUND'
    | 'ERR_HOST_BRIDGE'
    | 'ERR_BRIDGE_PAYLOAD_TOO_LARGE'
    | 'ERR_BRIDGE_CALL_LIMIT_EXCEEDED'
    /**
     * This run was an innocent victim: a co-resident run on the same shared
     * instance was interrupted mid-execution (CPU/memory guard or a forced
     * abort), so the instance could no longer be trusted and every run in
     * flight on it failed. Carries `resetCause` and `culpritRunId`; the
     * telemetry fields are this run's real partial values. Never retried
     * automatically — the victim may have had side effects.
     */
    | 'ERR_INSTANCE_RESET'
    | 'ERR_UNDECLARED_BINDING'
    /**
     * Prefix top-level evaluation never settled — nothing in the isolate
     * can resolve the awaited promise while a prefix evaluates (at
     * `prepare()` validation or at a run's prefix stage).
     */
    | 'ERR_PREFIX_DID_NOT_SETTLE'
    /**
     * Prefix code called a bridge callable (bridge global, shim global, or
     * host-import function). The bridge does not exist while a prefix
     * evaluates, so bridge calls in a prefix are not supported (yet) — do
     * the call in `run()` code instead.
     */
    | 'ERR_PREFIX_BRIDGE_CALL'
    /**
     * Warm-up (prefix evaluation + per-instance runtime installs) exceeded its fixed budget
     * (1 s wall / 1 s CPU — not configurable; Cloudflare's script-startup
     * model). Enforced at `prepare()` and again at every instance
     * cold-start. Move expensive setup into the handler: lazy init on first
     * call runs under that call's budget and survives warm reuse.
     */
    | 'ERR_WARMUP_LIMIT'
    | 'ERR_PREFIX_DISPOSED'
    /**
     * The runtime answered with a `Result` belonging to a different run, or
     * sent a frame that has no place in the run protocol. Host-detected, never
     * reported by the runtime: the two sides lost frame alignment on that
     * connection, so **this run never executed** — nothing ran, nothing was
     * observed, and the telemetry fields are zero rather than partial.
     *
     * The connection is destroyed and replaced before the result is returned,
     * so a retry runs on a fresh one. Seeing this at all is a bug worth
     * reporting; it should be unreachable.
     */
    | 'ERR_PROTOCOL_DESYNC'
    | 'ERR_INTERNAL'
